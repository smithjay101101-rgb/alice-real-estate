  function parseCSV(text) {
    var rows = [];
    var current = '';
    var inQuotes = false;
    var row = [];
    for (var i = 0; i < text.length; i++) {
      var ch = text[i];
      var next = text[i + 1];
      if (inQuotes) {
        if (ch === '"' && next === '"') { current += '"'; i++; }
        else if (ch === '"') { inQuotes = false; }
        else { current += ch; }
      } else {
        if (ch === '"') { inQuotes = true; }
        else if (ch === ',') { row.push(current.trim()); current = ''; }
        else if (ch === '\n' || (ch === '\r' && next === '\n')) {
          row.push(current.trim());
          if (row.length > 1) rows.push(row);
          row = []; current = '';
          if (ch === '\r') i++;
        } else { current += ch; }
      }
    }
    if (current || row.length) {
      row.push(current.trim());
      if (row.length > 1) rows.push(row);
    }
    return rows;
  }

  function generateCode(title) {
    var hash = 0;
    for (var i = 0; i < title.length; i++) {
      hash = ((hash << 5) - hash + title.charCodeAt(i)) | 0;
    }
    var num = Math.abs(hash) % 1000;
    return '#' + ('00' + num).slice(-3);
  }

  function mapRow(r) {
    var title = r[0] || '';
    return {
      title: title,
      location: r[1] || '',
      price: parseInt(r[2]) || 0,
      bedrooms: parseInt(r[3]) || 0,
      bathrooms: parseInt(r[4]) || 0,
      sqm: parseInt(r[5]) || 0,
      description: r[6] || '',
      imageMain: r[7] || '',
      imageGallery: r[8] ? r[8].split(',').map(function(u) { return u.trim(); }).filter(Boolean) : [],
      status: (r[9] || '').toLowerCase().trim(),
      featured: (r[10] || '').toLowerCase().trim() === 'yes',
      dateAdded: r[11] || '',
      code: generateCode(title)
    };
  }

  function slugify(text) {
    return text
      .toString()
      .toLowerCase()
      .trim()
      .replace(/[\s]+/g, '-')
      .replace(/[^\w\-]+/g, '')
      .replace(/\-\-+/g, '-')
      .replace(/^-+/, '')
      .replace(/-+$/, '');
  }

